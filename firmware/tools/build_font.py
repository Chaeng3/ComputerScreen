"""Render the installed Chinese font into a compact, fixed-cell bitmap.

Only run on this development PC; the ESP32 uses the generated binary directly.
Includes basic CJK so changing city does not require rebuilding the firmware.
"""
from pathlib import Path
from math import ceil
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1] / "main"
font = ImageFont.truetype("C:/Windows/Fonts/msyh.ttc", 16)
characters = [chr(c) for c in range(32, 127)] + ["°", "℃"] + [chr(c) for c in range(0x4E00, 0xA000)]
data = bytearray()
for char in characters:
    image = Image.new("L", (16, 20))
    ImageDraw.Draw(image).text((0, -2), char, font=font, fill=255)
    for y in range(20):
        for start in (0, 8):
            bits = sum((1 << (7 - x)) for x in range(8) if image.getpixel((start + x, y)) >= 96)
            data.append(bits)
(root / "font_cn16.bin").write_bytes(data)
widths = [min(16, max(4, ceil(font.getlength(chr(c))))) + 1 for c in range(32, 127)]
(root / "font_cn16_meta.h").write_text(
    "// Generated by tools/build_font.py; 16x20 pixels, 40 bytes per glyph.\n"
    "#pragma once\nstatic const uint8_t font_ascii_advance[95] = {\n    "
    + ",".join(map(str, widths)) + "\n};\n", encoding="utf-8")
print(f"Generated {len(characters)} glyphs, {len(data)} bytes")
